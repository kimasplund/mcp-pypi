def test_discovery_skips_vendor_dirs_and_caps(tmp_path):
    for rel in (
        "requirements.txt",
        "sub/pyproject.toml",
        ".venv/requirements.txt",
        "node_modules/x/requirements.txt",
        "build/setup.py",
        "a/b/c/d/e/requirements.txt",
    ):
        p = tmp_path / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text("")
    assert discover_dependency_files(tmp_path) == [
        tmp_path / "requirements.txt",
        tmp_path / "sub" / "pyproject.toml",
    ]
    assert len(discover_dependency_files(tmp_path, max_files=1)) == 1


def test_pip_compile_hashed_requirements(tmp_path):
    f = tmp_path / "requirements.txt"
    f.write_text(
        "#\n# This file is autogenerated by pip-compile\n#\n"
        "certifi==2024.2.2 \\\n"
        "    --hash=sha256:aaa \\\n"
        "    --hash=sha256:bbb\n"
        "    # via requests\n"
        "requests==2.31.0 \\\n"
        "    --hash=sha256:ccc \\\n"
        "    --hash=sha256:ddd\n"
        "    # via -r requirements.in\n"
    )
    assert pairs(parse_dependency_file(f)) == [
        ("certifi", "==2024.2.2"),
        ("requests", "==2.31.0"),
    ]


